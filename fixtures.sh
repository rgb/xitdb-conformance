#!/bin/sh
# Keeps fixtures/, the folder the Swift package copies into its test resources.
#
#   ./fixtures.sh           regenerates what has drifted from the scripts in this repository
#   ./fixtures.sh --check   changes nothing, and fails if anything has drifted
#
# Rerunning a script gives new commit IDs, so a fixture whose file differs only in
# those, and in the checksums they lead to, hasn't drifted, and it is left alone.
# Regenerating records the current commit as where the fixtures came from, so it
# needs everything outside fixtures/ to be committed.

set -eu
cd "$(dirname "$0")"

RUN=$PWD/zig-out/bin/run
DET=$PWD/zig-out/bin/detcheck
MANIFEST=$PWD/zig-out/bin/manifest
DUMP=$PWD/zig-out/bin/dump
# check.sh points this at a copy to show that --check notices drift
FIXTURES=${FIXTURES:-fixtures}
ZIG_ORIGINAL=../../xitdb
# the fixtures that come from another Zig commit, which the runner here can't check
ZIG_COMMITS=$PWD/tests/zig-commits.txt
# what the port refuses, so it runs on Zig and isn't a fixture
ZIG_ONLY=$PWD/tests/zig-only.txt
# the files scripts start from with raw_load, which are copied as they are
INPUTS=tests/inputs
# databases written by programs that use the original, copied as they are with dump's listing of each
SAMPLES=tests/samples

MODE=update
case "${1:-}" in
    "") ;;
    --check) MODE=check ;;
    *)
        echo "usage: ./fixtures.sh [--check]"
        exit 2
        ;;
esac

fail() {
    echo "fixtures: $1"
    exit 1
}

TMP=out/fixtures
rm -rf "$TMP"
mkdir -p "$TMP"

# sidecars with their commit IDs taken out, which is all they should differ in
without_commit_ids() {
    sed 's/"commit_id": "[0-9a-f]*"/"commit_id": "?"/' "$1"
}

same_sidecar_layout() {
    without_commit_ids "$1" > "$TMP/sidecar.a"
    without_commit_ids "$2" > "$TMP/sidecar.b"
    cmp -s "$TMP/sidecar.a" "$TMP/sidecar.b"
}

# what the fixtures are said to come from
git -C "$ZIG_ORIGINAL" diff --quiet HEAD || fail "the Zig original has uncommitted changes"
ZIG_COMMIT=$(git -C "$ZIG_ORIGINAL" rev-parse HEAD)
ZIG_VERSION=$(zig version)

recorded_commit() {
    sed -n 's/.*"conformance_commit": "\([0-9a-f]*\)".*/\1/p' "$FIXTURES/manifest.json"
}

write_manifest() { # conformance commit, output
    (
        cd "$FIXTURES"
        # a sidecar is a .json file too. the names have no spaces in them
        # shellcheck disable=SC2046
        "$MANIFEST" "$1" "$ZIG_COMMIT" "$ZIG_VERSION" "$ZIG_COMMITS" $(ls valid/*.json | grep -v '\.db\.sidecar\.json$') failing/*.json
    ) > "$2"
}

write_readme() { # conformance commit, output
    cat > "$2" <<EOF
# Conformance fixtures

What the Swift port of xitdb has to do, byte for byte, as Zig shows it. This is what Zig does, apart from the guards
\`SCRIPT-FORMAT.md\` says the port has, which \`run --port\` acts out on the Zig engine. This folder is generated by
\`./fixtures.sh\` in the conformance repository. Copy it as it stands, and don't edit it.

It was produced from:

- conformance repository: commit \`$1\`
- xitdb, the Zig original: commit \`$ZIG_COMMIT\`, or the one the manifest gives for that fixture as its \`zig_commit\`
- Zig $ZIG_VERSION, with the runner \`run\` built in debug mode and using the \`buffered_file\` storage kind

\`SCRIPT-FORMAT.md\` in the conformance repository describes the scripts, and how to run them.

## What's here

- \`manifest.json\`: every script, what it needs, and whether it should pass or fail. \`collections\` says which of
  \`array_list\`, \`hash_map\`, \`linked_array_list\` and \`sorted_map\` its path parts use, whether or not they're
  reached. \`features\` says which of these it uses: \`reopen\` (closing and reopening), \`raw_file\` (writing to the
  file directly while it's closed), \`read_only\` (opening it read-only, which the memory storage kind can't do),
  \`iterators\` (\`iterator\` and \`next\`), \`rank\`, \`byte_stream\` (\`read_stream\`), \`byte_buffers\`
  (\`read_bytes_into\`, and \`max_size\` on \`read_bytes\`) and \`inputs\` (\`raw_load\`).
- \`valid/<name>.json\`: a script that passes, with \`<name>.db\`, the file Zig wrote, and \`<name>.db.sidecar.json\`, its
  committed sizes and commit IDs. Those called \`<name>--port\` are the port's versions of scripts that pin what it
  refuses. Those called \`safe-*\` come from the generator with \`--port-safe\`. Those called \`gen-<seed>\`, \`reads-<seed>\`, \`compact-<seed>\` and \`replica-<seed>\` come from the generator \`gen\`, and
  are harder to read, but they do things in combinations nobody thought of. Those called \`deep-*\` have transactions of
  hundreds of writes, and they're what tells copying from rewriting in place. These and \`iterator-tiers*\` come from
  \`longscripts\`, because they're too long to write by hand.
- \`valid/<name>.<database>.db\`: for a script with several databases, each one's file. \`other_databases\` in the
  manifest lists them, and they're the ones the run left, which the sidecar's \`databases\` lists too, with \`main\`. A
  compaction that fails before it makes its target leaves no file for it, and nothing is listed.
- \`inputs/<name>.db\`: files that scripts start from, which \`raw_load\` puts in place of a database's file, and
  \`inputs\` in the manifest lists for each script. They aren't expected files, and they stay as they are when the
  fixtures follow another Zig commit. Those called \`v1-*\` are version 1 databases written by the original at
  \`6b93af1af3a260399fa0a0b1b268ded2cbf5eec5\`, as nothing writes a new one any more. \`tests/inputs/README.md\` in
  the conformance repository says where each came from and what's in it.
- \`samples/<program>/<name>.db\`: databases a program wrote through the original, with \`<name>.txt\`, what \`dump\` prints
  for each, which doesn't depend on where things are in the file, and the SHA-256 of each in \`SHA256SUMS\`. They're
  samples of real use, for a port's reading to be compared with the original's, and not byte-identity fixtures. Their
  \`README.md\` says what they are.
- \`failing/<name>.json\`: a well-formed script that must fail in every runner. The text after \`expected failure:\` in
  its description is why it fails in Zig, and it has no expected file, as there's nothing to compare.

## Which milestone a script waits for

The package's milestones go by what a script lists, and the highest of these is the one it waits for: \`replication\`
is M8, \`compaction\` is M7, \`sorted_map\` is M6, \`linked_array_list\` is M5, and \`iterators\`, \`rank\`, \`byte_stream\` or
\`byte_buffers\` is M4. Anything else runs at M3. A script with \`several_databases\` and no other reason to wait can
run as soon as the runner can make more than one.

## Using them

For a script in \`valid/\`, give the implementation a random source that returns the sidecar's non-null commit IDs in
order. After each top-level op, check the committed size against the sidecar. At the end, none of the commit IDs
should be left, and the file must equal \`<name>.db\` in every byte.

A script with several databases uses one list of commit IDs for all of them, in the order the sidecar has them, and an
entry's \`db\` says which database it's about. Every one of them has to equal its expected file.

For a script in \`failing/\`, the run must fail. Any commit IDs will do.

Every script here has passed through \`run\`, which validates a whole script before running any of it, so a runner
can assume they're well-formed.
EOF
}

# a fixture is what the port has to do, so all of them run with --port
SOURCES="scripts tests/valid tests/generated tests/port-variants"
# scripts that only pass on another Zig commit, which the gate doesn't run on this one
if [ -d tests/from-other-zig ]; then
    SOURCES="$SOURCES tests/from-other-zig"
fi
FAILING_SOURCES="tests/failing"

from_another_zig() { # name of a fixture
    grep -q "^$1 " "$ZIG_COMMITS"
}

zig_only() { # name of a script
    grep -q "^$1 " "$ZIG_ONLY"
}

if [ "$MODE" = check ]; then
    [ -f "$FIXTURES/manifest.json" ] || fail "there's no manifest. Run ./fixtures.sh"
    elsewhere=0

    # the samples, and what dump makes of them now
    for dir in "$SAMPLES"/*/; do
        [ -d "$dir" ] || continue
        program=$(basename "$dir")
        (cd "$dir" && shasum -a 256 -c SHA256SUMS > /dev/null) || fail "the samples in $dir aren't the ones SHA256SUMS names"
        for file in "$dir"*; do
            cmp -s "$file" "$FIXTURES/samples/$program/$(basename "$file")" || fail "the sample $program/$(basename "$file") differs from the one in $dir, or is missing"
        done
        for database in "$dir"*.db; do
            name=$(basename "$database" .db)
            "$DUMP" "$database" > "$TMP/sample.txt" || fail "dump can't read the sample $program/$name"
            cmp -s "$TMP/sample.txt" "$FIXTURES/samples/$program/$name.txt" || fail "dump's listing of the sample $program/$name has drifted"
        done
    done
    for file in "$FIXTURES"/samples/*/*; do
        [ -e "$file" ] || continue
        program=$(basename "$(dirname "$file")")
        name=$(basename "$file")
        [ -f "$SAMPLES/$program/$name" ] || [ -f "$SAMPLES/$program/${name%.txt}.db" ] || fail "$file has no source in $SAMPLES"
    done

    # the inputs first, as the scripts that load them would only drift
    for input in "$INPUTS"/*.db; do
        [ -e "$input" ] || continue
        cmp -s "$input" "$FIXTURES/inputs/$(basename "$input")" || fail "the input $(basename "$input") differs from the one in $INPUTS, or is missing"
    done
    for file in "$FIXTURES"/inputs/*; do
        [ -e "$file" ] || continue
        [ -f "$INPUTS/$(basename "$file")" ] || fail "$file has no source in $INPUTS"
    done

    # every source script is here unchanged, and passes from its copy here
    for dir in $SOURCES; do
        for script in "$dir"/*.json; do
            name=$(basename "$script" .json)
            if zig_only "$name"; then continue; fi
            copy="$FIXTURES/valid/$name.json"
            [ -f "$copy" ] || fail "$name is missing from $FIXTURES/valid"
            cmp -s "$script" "$copy" || fail "$name differs from the script in $dir"
            [ -f "$FIXTURES/valid/$name.db" ] || fail "$name has no expected file"
            [ -f "$FIXTURES/valid/$name.db.sidecar.json" ] || fail "$name has no sidecar"
            if from_another_zig "$name"; then
                elsewhere=$((elsewhere + 1))
                continue
            fi
            "$RUN" "$copy" "$TMP/$name.db" --port --inputs "$FIXTURES/inputs" || fail "$name no longer runs"
            "$DET" "$TMP/$name.db" "$FIXTURES/valid/$name.db" > /dev/null || fail "$name has drifted"
            same_sidecar_layout "$TMP/$name.db.sidecar.json" "$FIXTURES/valid/$name.db.sidecar.json" || fail "$name's sidecar has drifted"
        done
    done
    for script in $FAILING_SOURCES/*.json; do
        name=$(basename "$script" .json)
        copy="$FIXTURES/failing/$name.json"
        [ -f "$copy" ] || fail "$name is missing from $FIXTURES/failing"
        cmp -s "$script" "$copy" || fail "$name differs from the script in $FAILING_SOURCES"
        status=0
        "$RUN" "$copy" "$TMP/$name.db" --port 2> /dev/null || status=$?
        [ "$status" -eq 1 ] || fail "$name should fail, but its exit status is $status"
    done

    # and nothing else is here
    for file in "$FIXTURES"/valid/*; do
        case "$file" in
            *.db.sidecar.json) name=$(basename "$file" .db.sidecar.json) ;;
            *.db)
                # <name>.db, or <name>.<database>.db, which the manifest has to list
                base=$(basename "$file" .db)
                name=${base%%.*}
                if [ "$name" != "$base" ]; then
                    grep -qF "\"valid/$base.db\"" "$FIXTURES/manifest.json" || fail "$file has no source script"
                fi
                ;;
            *.json) name=$(basename "$file" .json) ;;
            *) fail "$file shouldn't be here" ;;
        esac
        found=no
        for dir in $SOURCES; do
            [ -f "$dir/$name.json" ] && found=yes
        done
        if zig_only "$name"; then found=no; fi
        [ "$found" = yes ] || fail "$file has no source script"
    done
    for file in "$FIXTURES"/failing/*; do
        [ -f "$FAILING_SOURCES/$(basename "$file")" ] || fail "$file has no source script"
    done

    # every path the manifest names is here. a path is any string in it that ends in .db or .json
    grep -oE '"[^"]+\.(db|json)"' "$FIXTURES/manifest.json" | tr -d '"' | sort -u > "$TMP/named.txt"
    while read -r path; do
        [ -f "$FIXTURES/$path" ] || fail "the manifest names $path, which isn't in $FIXTURES"
    done < "$TMP/named.txt"
    # and everything here is named by the manifest, or is one of what the README lists that isn't a script's
    (cd "$FIXTURES" && find . -mindepth 1 | sed 's|^\./||' | sort) > "$TMP/here.txt"
    while read -r path; do
        unlisted="$FIXTURES/$path is neither named by the manifest nor one of the files the README says are here"
        if [ -d "$FIXTURES/$path" ]; then
            case "$path" in
                valid | failing | inputs | samples) ;;
                samples/*/*) fail "$unlisted" ;;
                samples/*) ;;
                *) fail "$unlisted" ;;
            esac
            continue
        fi
        [ -f "$FIXTURES/$path" ] || fail "$unlisted"
        case "$path" in
            manifest.json | README.md) ;;
            valid/* | failing/*) grep -qxF "$path" "$TMP/named.txt" || fail "$FIXTURES/$path isn't named by the manifest" ;;
            # what scripts start from, which have a source in tests/inputs, as checked above
            inputs/*/*) fail "$unlisted" ;;
            inputs/*.db) ;;
            # each sample with dump's listing of it, the checksums, and what they are
            samples/*/*/*) fail "$unlisted" ;;
            samples/*/README.md | samples/*/SHA256SUMS) ;;
            samples/*/*.db)
                [ -f "$FIXTURES/${path%.db}.txt" ] || fail "the sample $path has no listing beside it"
                awk -v name="$(basename "$path")" '$2 == name { found = 1 } END { exit !found }' "$(dirname "$FIXTURES/$path")/SHA256SUMS" 2> /dev/null ||
                    fail "the sample $path isn't in SHA256SUMS"
                ;;
            samples/*/*.txt) [ -f "$FIXTURES/${path%.txt}.db" ] || fail "$unlisted" ;;
            *) fail "$unlisted" ;;
        esac
    done < "$TMP/here.txt"

    # the commit they say they came from is in this repository's history
    commit=$(recorded_commit)
    [ -n "$commit" ] || fail "the manifest doesn't say which commit it came from"
    git merge-base --is-ancestor "$commit" HEAD 2> /dev/null || fail "commit $commit isn't in this branch's history"

    # the rest is generated from what's checked above, and the Zig original
    write_manifest "$commit" "$TMP/manifest.json"
    cmp -s "$TMP/manifest.json" "$FIXTURES/manifest.json" || fail "manifest.json has drifted"
    write_readme "$commit" "$TMP/README.md"
    cmp -s "$TMP/README.md" "$FIXTURES/README.md" || fail "README.md has drifted"

    valid=$(find "$FIXTURES/valid" -name '*.db' | wc -l | tr -d ' ')
    failing=$(find "$FIXTURES/failing" -name '*.json' | wc -l | tr -d ' ')
    inputs=$(find "$FIXTURES/inputs" -name '*.db' 2> /dev/null | wc -l | tr -d ' ')
    samples=$(find "$FIXTURES/samples" -name '*.db' 2> /dev/null | wc -l | tr -d ' ')
    echo "$FIXTURES: $valid expected files, $failing failing scripts, $inputs inputs and $samples samples haven't drifted"
    if [ "$elsewhere" -gt 0 ]; then
        echo "$elsewhere of those are from another Zig commit, so they weren't run here. ./second-zig.sh runs them"
    fi
    exit 0
fi

if [ -n "$(git status --porcelain -- . ":(exclude)$FIXTURES")" ]; then
    fail "commit everything outside $FIXTURES first, so that the fixtures can say which commit they came from"
fi
HEAD_COMMIT=$(git rev-parse HEAD)

mkdir -p "$FIXTURES/valid" "$FIXTURES/failing" "$FIXTURES/inputs"
changed=no

for input in "$INPUTS"/*.db; do
    [ -e "$input" ] || continue
    copy="$FIXTURES/inputs/$(basename "$input")"
    if ! cmp -s "$input" "$copy"; then
        cp "$input" "$copy"
        echo "wrote $copy"
        changed=yes
    fi
done
for file in "$FIXTURES"/inputs/*; do
    [ -e "$file" ] || continue
    [ -f "$INPUTS/$(basename "$file")" ] && continue
    rm "$file"
    echo "removed $file"
    changed=yes
done

rm -rf "$TMP/samples"
for dir in "$SAMPLES"/*/; do
    [ -d "$dir" ] || continue
    program=$(basename "$dir")
    (cd "$dir" && shasum -a 256 -c SHA256SUMS > /dev/null) || fail "the samples in $dir aren't the ones SHA256SUMS names"
    mkdir -p "$TMP/samples/$program"
    cp "$dir"* "$TMP/samples/$program/"
    for database in "$dir"*.db; do
        "$DUMP" "$database" > "$TMP/samples/$program/$(basename "$database" .db).txt" || fail "dump can't read the sample $database"
    done
done
if [ -d "$TMP/samples" ]; then
    if ! diff -r "$TMP/samples" "$FIXTURES/samples" > /dev/null 2>&1; then
        rm -rf "$FIXTURES/samples"
        cp -R "$TMP/samples" "$FIXTURES/samples"
        echo "wrote $FIXTURES/samples"
        changed=yes
    fi
elif [ -d "$FIXTURES/samples" ]; then
    rm -rf "$FIXTURES/samples"
    echo "removed $FIXTURES/samples"
    changed=yes
fi

# what isn't a source script any more goes
for file in "$FIXTURES"/valid/* "$FIXTURES"/failing/*; do
    [ -e "$file" ] || continue
    case "$file" in
        "$FIXTURES"/failing/*)
            [ -f "$FAILING_SOURCES/$(basename "$file")" ] && continue
            ;;
        *)
            name=$(basename "$file")
            name=${name%%.*}
            found=no
            for dir in $SOURCES; do
                [ -f "$dir/$name.json" ] && found=yes
            done
            if zig_only "$name"; then found=no; fi
            [ "$found" = yes ] && continue
            ;;
    esac
    rm "$file"
    echo "removed $file"
    changed=yes
done

for dir in $SOURCES; do
    for script in "$dir"/*.json; do
        name=$(basename "$script" .json)
        if zig_only "$name"; then continue; fi
        copy="$FIXTURES/valid/$name"
        # these came from second-zig.sh, and the runner here has no say in them
        if from_another_zig "$name"; then
            if ! cmp -s "$script" "$copy.json"; then
                cp "$script" "$copy.json"
                echo "wrote $copy.json"
                changed=yes
            fi
            continue
        fi
        "$RUN" "$script" "$TMP/$name.db" --port
        if [ -f "$copy.json" ] && [ -f "$copy.db" ] && [ -f "$copy.db.sidecar.json" ] &&
            cmp -s "$script" "$copy.json" &&
            "$DET" "$TMP/$name.db" "$copy.db" > /dev/null 2>&1 &&
            same_sidecar_layout "$TMP/$name.db.sidecar.json" "$copy.db.sidecar.json"; then
            continue
        fi
        cp "$script" "$copy.json"
        cp "$TMP/$name.db" "$copy.db"
        cp "$TMP/$name.db.sidecar.json" "$copy.db.sidecar.json"
        # the other databases are the ones this run left, and only those
        rm -f "$FIXTURES/valid/$name".*.db
        for other in "$TMP/$name".*.db; do
            [ -e "$other" ] || continue
            cp "$other" "$FIXTURES/valid/$(basename "$other")"
        done
        echo "wrote $copy"
        changed=yes
    done
done

for script in $FAILING_SOURCES/*.json; do
    name=$(basename "$script" .json)
    status=0
    "$RUN" "$script" "$TMP/$name.db" --port 2> /dev/null || status=$?
    [ "$status" -eq 1 ] || fail "$name should fail, but its exit status is $status"
    copy="$FIXTURES/failing/$name.json"
    if ! cmp -s "$script" "$copy"; then
        cp "$script" "$copy"
        echo "wrote $copy"
        changed=yes
    fi
done

# the commit only moves if something else did, as otherwise nothing came from it
commit=$HEAD_COMMIT
if [ -f "$FIXTURES/manifest.json" ] && [ "$changed" = no ]; then
    commit=$(recorded_commit)
    write_manifest "$commit" "$TMP/manifest.json"
    write_readme "$commit" "$TMP/README.md"
    if cmp -s "$TMP/manifest.json" "$FIXTURES/manifest.json" && cmp -s "$TMP/README.md" "$FIXTURES/README.md"; then
        echo "$FIXTURES: nothing has drifted"
        exit 0
    fi
    commit=$HEAD_COMMIT
fi
write_manifest "$commit" "$TMP/manifest.json"
cp "$TMP/manifest.json" "$FIXTURES/manifest.json"
write_readme "$commit" "$FIXTURES/README.md"
echo "$FIXTURES: regenerated, from commit $commit"
